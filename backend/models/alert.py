"""
NetSentinel AI
Module 6 - Threat Detection & Alert Management

Database model for security alerts generated by the
AI intrusion detection engine.
"""

from __future__ import annotations

from datetime import datetime, timezone

from extensions.database import db


class Alert(db.Model):
    """
    Represents a security alert generated by NetSentinel AI.
    """

    __tablename__ = "alerts"

    id = db.Column(db.Integer, primary_key=True)

    # Alert identification
    alert_type = db.Column(
        db.String(100),
        nullable=False,
        index=True,
    )

    title = db.Column(
        db.String(200),
        nullable=False,
    )

    description = db.Column(
        db.Text,
        nullable=False,
    )

    # Severity and AI confidence
    severity = db.Column(
        db.String(20),
        nullable=False,
        default="LOW",
        index=True,
    )

    confidence = db.Column(
        db.Float,
        nullable=False,
        default=0.0,
    )

    probability = db.Column(
        db.Float,
        nullable=False,
        default=0.0,
    )

    # Network information
    source_ip = db.Column(
        db.String(45),
        nullable=True,
        index=True,
    )

    destination_ip = db.Column(
        db.String(45),
        nullable=True,
        index=True,
    )

    source_port = db.Column(
        db.Integer,
        nullable=True,
    )

    destination_port = db.Column(
        db.Integer,
        nullable=True,
    )

    protocol = db.Column(
        db.String(20),
        nullable=True,
    )

    # Alert lifecycle
    status = db.Column(
        db.String(20),
        nullable=False,
        default="OPEN",
        index=True,
    )

    # User assignment
    acknowledged_by = db.Column(
        db.Integer,
        db.ForeignKey("users.id"),
        nullable=True,
    )

    resolved_by = db.Column(
        db.Integer,
        db.ForeignKey("users.id"),
        nullable=True,
    )

    # Timestamps
    created_at = db.Column(
        db.DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        index=True,
    )

    acknowledged_at = db.Column(
        db.DateTime(timezone=True),
        nullable=True,
    )

    resolved_at = db.Column(
        db.DateTime(timezone=True),
        nullable=True,
    )

    # Additional detection data
    detection_data = db.Column(
        db.JSON,
        nullable=True,
    )

    def to_dict(self) -> dict:
        """Return a JSON-safe representation of the alert."""

        return {
            "id": self.id,
            "alert_type": self.alert_type,
            "title": self.title,
            "description": self.description,
            "severity": self.severity,
            "confidence": self.confidence,
            "probability": self.probability,
            "source_ip": self.source_ip,
            "destination_ip": self.destination_ip,
            "source_port": self.source_port,
            "destination_port": self.destination_port,
            "protocol": self.protocol,
            "status": self.status,
            "acknowledged_by": self.acknowledged_by,
            "resolved_by": self.resolved_by,
            "created_at": (
                self.created_at.isoformat()
                if self.created_at
                else None
            ),
            "acknowledged_at": (
                self.acknowledged_at.isoformat()
                if self.acknowledged_at
                else None
            ),
            "resolved_at": (
                self.resolved_at.isoformat()
                if self.resolved_at
                else None
            ),
            "detection_data": self.detection_data,
        }

    def __repr__(self) -> str:
        return (
            f"<Alert id={self.id} "
            f"type={self.alert_type!r} "
            f"severity={self.severity!r} "
            f"status={self.status!r}>"
        )